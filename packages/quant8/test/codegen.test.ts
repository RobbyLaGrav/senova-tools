import assert from "node:assert/strict"
import { test } from "node:test"

import { generateC, memoryEstimate, parseModel, quantize } from "../src/index.ts"
import { randomInputs, randomModelJson } from "./helpers.ts"

const q3 = quantize(parseModel(randomModelJson([6, 10, 7, 4], 21, true)), randomInputs(50, 6, 22))
const q1 = quantize(parseModel(randomModelJson([3, 2], 23)), randomInputs(10, 3, 24))

/** The part of the source that must compile without floating point: everything before the float helpers. */
const integerPart = (src: string, N: string) => stripComments(src.slice(0, src.indexOf(`#ifndef ${N}_NO_FLOAT`)))
const stripComments = (src: string) => src.replace(/\/\*[\s\S]*?\*\//g, "")

test("header: guard, sizes, zero points, prototypes and the float switch", () => {
  const { header, headerName } = generateC(q3, { name: "kws" })
  assert.equal(headerName, "kws.h")
  assert.match(header, /^\/\* kws\.h: int8 network generated by quant8/)
  assert.match(header, /#ifndef KWS_H\n#define KWS_H\n/)
  assert.match(header, /#include <stdint\.h>/)
  assert.match(header, /#define KWS_INPUT_SIZE 6\n#define KWS_OUTPUT_SIZE 4\n/)
  assert.match(header, new RegExp(`#define KWS_INPUT_ZERO_POINT ${q3.input.zeroPoint}\\n`))
  assert.match(header, /void kws_predict\(const int8_t \*input, int8_t \*output\);/)
  assert.match(header, /int kws_argmax\(const int8_t \*output\);/)
  assert.match(header, /#ifndef KWS_NO_FLOAT\n#define KWS_INPUT_SCALE /)
  assert.match(header, /extern "C"/)
  assert.match(header, /Layers: 6 -> 10 relu -> 7 relu -> 4 -> softmax/)
  assert.ok(header.trimEnd().endsWith("#endif /* KWS_H */"))
  // Scales (floats) only appear inside the float section.
  assert.doesNotMatch(integerPart(header, "KWS"), /SCALE|float|double/)
})

test("source: const arrays of the right lengths, static scratch, no malloc and no float in the integer path", () => {
  const { source, sourceName } = generateC(q3, { name: "kws" })
  assert.equal(sourceName, "kws.c")
  q3.layers.forEach((l, i) => {
    assert.match(source, new RegExp(`static const int8_t kws_l${i}_w\\[${l.inputs * l.outputs}\\] = \\{`))
    assert.match(source, new RegExp(`static const int32_t kws_l${i}_b\\[${l.outputs}\\] = \\{`))
    assert.match(source, new RegExp(`static const int32_t kws_l${i}_m\\[${l.outputs}\\] = \\{`))
    assert.match(source, new RegExp(`static const int8_t kws_l${i}_s\\[${l.outputs}\\] = \\{`))
    const w = source.split(`kws_l${i}_w[${l.inputs * l.outputs}] = {`)[1]!.split("};")[0]!
    assert.deepEqual(w.split(",").map((s) => Number(s.trim())), Array.from(l.weights))
  })
  assert.match(source, /static int8_t kws_buf0\[10\];\nstatic int8_t kws_buf1\[10\];/)
  assert.match(source, /kws_dense\(input, kws_buf0, 6, 10,/)
  assert.match(source, /kws_dense\(kws_buf0, kws_buf1, 10, 7,/)
  assert.match(source, /kws_dense\(kws_buf1, output, 7, 4,/)
  assert.doesNotMatch(stripComments(source), /malloc|calloc|free\(|<stdlib\.h>/)
  assert.doesNotMatch(integerPart(source, "KWS"), /\bfloat\b|\bdouble\b|math\.h/)
  assert.match(source, /#ifndef KWS_NO_FLOAT\n#include <math\.h>/)
  assert.match(source, /expf/) // softmax in the float helper
})

test("one-layer model: no scratch buffers, writes straight to output, no softmax helper", () => {
  const { source } = generateC(q1)
  assert.doesNotMatch(source, /model_buf/)
  assert.match(source, /model_dense\(input, output, 3, 2,/)
  assert.doesNotMatch(source, /expf/)
  assert.equal(memoryEstimate(q1).ramBytes, 0)
})

test("memory estimate counts const data and scratch", () => {
  const m = memoryEstimate(q3)
  assert.equal(m.flashBytes, 6 * 10 + 10 * 7 + 7 * 4 + 9 * (10 + 7 + 4))
  assert.equal(m.ramBytes, 20)
  assert.equal(m.ioBytes, 10)
})

test("names must be C identifiers", () => {
  for (const bad of ["Model", "1net", "my-net", "", "a b", "x".repeat(50)]) assert.throws(() => generateC(q1, { name: bad }), /C identifier/)
})

test("generation is deterministic", () => {
  assert.equal(generateC(q3).source, generateC(q3).source)
})
