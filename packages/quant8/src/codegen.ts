// C99 code generation: one header and one source file, const weight arrays (flash), two static scratch buffers (RAM),
// no malloc and no floating point in <name>_predict. Optional float helpers sit behind <NAME>_NO_FLOAT.
import { INT32_MIN } from "./fixedpoint.ts"
import { Quant8Error } from "./model.ts"
import type { QuantModel } from "./quantize.ts"

export interface GenerateOptions {
  /** C identifier prefix and file name (default "model"). Lower case letters, digits and underscores. */
  name?: string
}

export interface GeneratedC {
  headerName: string
  sourceName: string
  header: string
  source: string
}

export interface MemoryEstimate {
  /** Bytes of const data (weights, biases, multipliers, shifts). Code size is not included: it depends on the compiler. */
  flashBytes: number
  /** Bytes of static scratch buffers inside the generated file. The caller's input and output arrays are extra. */
  ramBytes: number
  /** Caller-owned bytes: the int8 input and output arrays. */
  ioBytes: number
  layers: { weights: number; bias: number; multipliers: number; shifts: number }[]
}

/** Byte estimates for the generated C. */
export function memoryEstimate(q: QuantModel): MemoryEstimate {
  const layers = q.layers.map((l) => ({ weights: l.weights.length, bias: 4 * l.outputs, multipliers: 4 * l.outputs, shifts: l.outputs }))
  const flashBytes = layers.reduce((s, l) => s + l.weights + l.bias + l.multipliers + l.shifts, 0)
  return { flashBytes, ramBytes: scratchCount(q) * scratchSize(q), ioBytes: q.inputSize + q.layers.at(-1)!.outputs, layers }
}

/** Width of each scratch buffer: the widest layer output that is not the final output (0 for one layer). */
const scratchSize = (q: QuantModel): number => q.layers.slice(0, -1).reduce((m, l) => Math.max(m, l.outputs), 0)
/** Scratch buffers used: none for one layer, one for two layers, two (ping-pong) for more. */
const scratchCount = (q: QuantModel): number => Math.min(2, q.layers.length - 1)

const NAME_RE = /^[a-z_][a-z0-9_]{0,40}$/

/** Checks a C prefix. */
export function checkName(name: string): string {
  if (!NAME_RE.test(name)) throw new Quant8Error(`name ${JSON.stringify(name)} must be a C identifier: lower case letters, digits and _, starting with a letter or _`)
  return name
}

/** An int32 as a C literal. -2147483648 is not a valid literal on its own in C. */
const cInt32 = (v: number): string => (v === INT32_MIN ? "(-2147483647 - 1)" : String(v))

/** A double as a C literal that round-trips. */
const cDouble = (v: number): string => {
  const s = String(v)
  return /[.e]/.test(s) ? s : `${s}.0`
}

/** Formats numbers as C initialiser rows, 16 per line. */
function cArray(values: ArrayLike<number>, fmt: (v: number) => string = String): string {
  const out: string[] = []
  for (let i = 0; i < values.length; i += 16) out.push("    " + Array.from(values).slice(i, i + 16).map(fmt).join(", "))
  return out.join(",\n")
}

/** Generates the .h and .c pair for a quantised model. */
export function generateC(q: QuantModel, options: GenerateOptions = {}): GeneratedC {
  const name = checkName(options.name ?? "model")
  const N = name.toUpperCase()
  const last = q.layers.length - 1
  const outSize = q.layers[last]!.outputs
  const mem = memoryEstimate(q)
  const scratch = scratchSize(q)
  const desc =
    `${q.inputSize} -> ` + q.layers.map((l) => `${l.outputs}${l.activation === "relu" ? " relu" : ""}`).join(" -> ") + (q.softmax ? " -> softmax" : "")

  const header = `/* ${name}.h: int8 network generated by quant8 (${q.scheme} activations). Do not edit; regenerate instead.
 * Layers: ${desc}
 * Flash (const data): ${mem.flashBytes} bytes. RAM (static scratch): ${mem.ramBytes} bytes, plus your input and output arrays.
 * ${name}_predict uses integers only. Define ${N}_NO_FLOAT to leave out the float helpers. */
#ifndef ${N}_H
#define ${N}_H

#include <stdint.h>

#define ${N}_INPUT_SIZE ${q.inputSize}
#define ${N}_OUTPUT_SIZE ${outSize}
#define ${N}_INPUT_ZERO_POINT ${q.input.zeroPoint}
#define ${N}_OUTPUT_ZERO_POINT ${q.output.zeroPoint}

#ifdef __cplusplus
extern "C" {
#endif

/* Runs the network on an int8 input and writes the int8 output. Not reentrant: it uses static scratch buffers. */
void ${name}_predict(const int8_t *input, int8_t *output);

/* Index of the largest output (the predicted class; softmax would not change it). */
int ${name}_argmax(const int8_t *output);

#ifndef ${N}_NO_FLOAT
#define ${N}_INPUT_SCALE ${cDouble(q.input.scale)}
#define ${N}_OUTPUT_SCALE ${cDouble(q.output.scale)}
/* real -> int8 with the input scale and zero point. */
void ${name}_quantize_input(const float *input, int8_t *output);
/* int8 -> real${q.softmax ? ", then softmax" : ""}. */
void ${name}_dequantize_output(const int8_t *input, float *output);
#endif

#ifdef __cplusplus
}
#endif

#endif /* ${N}_H */
`

  const layerData = q.layers
    .map(
      (l, i) => `/* Layer ${i}: ${l.inputs} -> ${l.outputs}, ${l.activation}. Input zero point ${l.input.zeroPoint}, output zero point ${l.output.zeroPoint}. */
static const int8_t ${name}_l${i}_w[${l.outputs * l.inputs}] = {
${cArray(l.weights)}
};
static const int32_t ${name}_l${i}_b[${l.outputs}] = {
${cArray(l.bias, cInt32)}
};
static const int32_t ${name}_l${i}_m[${l.outputs}] = {
${cArray(l.multipliers, cInt32)}
};
static const int8_t ${name}_l${i}_s[${l.outputs}] = {
${cArray(l.shifts)}
};
`,
    )
    .join("\n")

  const calls = q.layers
    .map((l, i) => {
      const src = i === 0 ? "input" : `${name}_buf${(i - 1) % 2}`
      const dst = i === last ? "output" : `${name}_buf${i % 2}`
      return `    ${name}_dense(${src}, ${dst}, ${l.inputs}, ${l.outputs}, ${name}_l${i}_w, ${name}_l${i}_b, ${name}_l${i}_m, ${name}_l${i}_s, ${l.input.zeroPoint}, ${l.output.zeroPoint}, ${l.actMin});`
    })
    .join("\n")

  const softmaxC = q.softmax
    ? `
    {
        float m = output[0], s = 0.0f;
        for (i = 1; i < ${N}_OUTPUT_SIZE; i++) if (output[i] > m) m = output[i];
        for (i = 0; i < ${N}_OUTPUT_SIZE; i++) { output[i] = expf(output[i] - m); s += output[i]; }
        for (i = 0; i < ${N}_OUTPUT_SIZE; i++) output[i] /= s;
    }`
    : ""

  const source = `/* ${name}.c: int8 network generated by quant8. Do not edit; regenerate instead. C99, no malloc. */
#include "${name}.h"

${layerData}
${Array.from({ length: scratchCount(q) }, (_, i) => `static int8_t ${name}_buf${i}[${scratch}];\n`).join("")}
/* round(a * b / 2^31), exact ties up; saturates the single overflow case. */
static int32_t ${name}_srdhm(int32_t a, int32_t b)
{
    int64_t ab, nudge;
    if (a == (-2147483647 - 1) && b == (-2147483647 - 1)) return 2147483647;
    ab = (int64_t)a * (int64_t)b;
    nudge = ab >= 0 ? ((int64_t)1 << 30) : (1 - ((int64_t)1 << 30));
    return (int32_t)((ab + nudge) / ((int64_t)1 << 31));
}

/* x / 2^e rounded to nearest, ties away from zero. Written without shifting negative numbers, which C99 leaves to the compiler. */
static int32_t ${name}_rdbp(int32_t x, int e)
{
    int64_t p = (int64_t)1 << e;
    int64_t v = x;
    int64_t fl = v >= 0 ? v / p : -((-v - 1) / p) - 1;
    int64_t rem = v - fl * p;
    int64_t threshold = ((p - 1) >> 1) + (v < 0 ? 1 : 0);
    return (int32_t)(fl + (rem > threshold ? 1 : 0));
}

static int8_t ${name}_requant(int32_t acc, int32_t m, int shift, int32_t zp, int32_t lo)
{
    int64_t x = (int64_t)acc;
    int64_t y;
    if (shift > 0) {
        x *= ((int64_t)1 << shift);
        if (x > 2147483647) x = 2147483647;
        if (x < -2147483647 - 1) x = -2147483647 - 1;
    }
    y = (int64_t)${name}_rdbp(${name}_srdhm((int32_t)x, m), shift > 0 ? 0 : -shift) + zp;
    if (y < lo) y = lo;
    if (y > 127) y = 127;
    return (int8_t)y;
}

static void ${name}_dense(const int8_t *in, int8_t *out, int n_in, int n_out, const int8_t *w, const int32_t *b,
                          const int32_t *m, const int8_t *s, int32_t in_zp, int32_t out_zp, int32_t lo)
{
    int o, i;
    for (o = 0; o < n_out; o++) {
        const int8_t *row = w + (int32_t)o * n_in;
        int32_t acc = b[o];
        for (i = 0; i < n_in; i++) acc += (int32_t)row[i] * ((int32_t)in[i] - in_zp);
        out[o] = ${name}_requant(acc, m[o], s[o], out_zp, lo);
    }
}

void ${name}_predict(const int8_t *input, int8_t *output)
{
${calls}
}

int ${name}_argmax(const int8_t *output)
{
    int i, best = 0;
    for (i = 1; i < ${N}_OUTPUT_SIZE; i++) if (output[i] > output[best]) best = i;
    return best;
}

#ifndef ${N}_NO_FLOAT
#include <math.h>

void ${name}_quantize_input(const float *input, int8_t *output)
{
    int i;
    for (i = 0; i < ${N}_INPUT_SIZE; i++) {
        double v = round((double)input[i] / ${N}_INPUT_SCALE) + ${N}_INPUT_ZERO_POINT;
        if (v < -128.0) v = -128.0;
        if (v > 127.0) v = 127.0;
        output[i] = (int8_t)v;
    }
}

void ${name}_dequantize_output(const int8_t *input, float *output)
{
    int i;
    for (i = 0; i < ${N}_OUTPUT_SIZE; i++) output[i] = (float)(${N}_OUTPUT_SCALE * (double)(input[i] - ${N}_OUTPUT_ZERO_POINT));${softmaxC}
}
#endif
`
  return { headerName: `${name}.h`, sourceName: `${name}.c`, header, source }
}
